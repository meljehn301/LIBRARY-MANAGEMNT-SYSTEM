    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
    String bookID = jTextField1.getText();
    String studentID = jTextField2.getText();

    try {
        Connection con = ConnectionProvider.getCon();
        Statement st = con.createStatement();

        ResultSet rs = st.executeQuery(
            "SELECT * FROM issue WHERE bookID = '" + bookID
            + "' AND studentID = '" + studentID + "'"
        );

        if (rs.next()) {
            jTextField3.setText(rs.getString(3));
            jTextField4.setText(rs.getString(4));

            jTextField1.setEditable(false);
            jTextField2.setEditable(false);
        } else {
            JOptionPane.showMessageDialog(
                this, "Book is not issued to this student"
            );
        }

        rs.close();
        st.close();
        con.close();

            } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this, "Connection Error: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   // TODO add your handling code here:

    String bookID = jTextField1.getText().trim();
    String studentID = jTextField2.getText().trim();

    try {
        Connection con = ConnectionProvider.getCon();
        Statement st = con.createStatement();

        int rows = st.executeUpdate(
            "UPDATE issue SET returnBook='YES' WHERE bookID='"
            + bookID + "' AND studentID='" + studentID + "'"
        );

        if (rows > 0) {
            JOptionPane.showMessageDialog(
                this, "Book successfully returned"
            );

            setVisible(false);
            new returnBook().setVisible(true);
        } else {
            JOptionPane.showMessageDialog(
                this, "No matching issued book found"
            );
        }

        st.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this, "Connection Error: " + e.getMessage()
        );
    }
    {
            try {
        String sql = "INSERT INTO returnbook (bookID, studentID, issueDate, dueDate) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, jTextField1.getText());
        pst.setString(2, jTextField2.getText());
        pst.setString(3, jTextField3.getText());
        pst.setString(4, jTextField4.getText());// ⚠️ better to hash password later
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "✅ User saved successfully!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "❌ Insert Error: " + e.getMessage());
    }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

